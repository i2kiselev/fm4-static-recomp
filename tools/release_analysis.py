"""Resolve the analysis for the code image of a game folder, before codegen.

    release_analysis.py --game-root <extracted Disc 1>
    release_analysis.py --refresh        # the game root of the last run (tools/build.ps1)

Finds the release by default.xex's SHA-256 (config/supported-discs.json) and writes, into
.local/generated/<code image>/: the rexglue manifest, analysis/main-xex.toml with every
canonical address moved through the image's port table (and its fragment list included), and
guest_addresses.h for the C++ hooks. .local/generated/code-image.cmake names the image for
CMake. Files are rewritten only when their content changes, so a build recompiles nothing
that did not change. Any canonical address without a port stops with its name.
"""
import argparse
import re
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import code_images as ci  # noqa: E402

GENERATED = ci.ROOT / ".local/generated"
SELECTOR = GENERATED / "code-image.cmake"
MANIFEST_TEMPLATE = ci.REXGLUE_CONFIG / "fm4_manifest.toml"
TEMPLATE_GAME_ROOT = "../../../extracted/fm4"
ADDRESS = re.compile(r"0x8[0-9A-Fa-f]{7}")


def image_dir(image: str) -> Path:
    return GENERATED / image


def manifest_path(image: str) -> Path:
    return image_dir(image) / "fm4_manifest.toml"


def fragments_path(image: str) -> Path:
    return ci.REXGLUE_CONFIG / f"analysis/fragments-{image}.toml"


def current_game_root() -> Path:
    """The game root of the last resolution."""
    image = re.search(r'set\(FM4_CODE_IMAGE "([^"]+)"\)', SELECTOR.read_text(encoding="utf-8")) \
        if SELECTOR.is_file() else None
    if image is None or not manifest_path(image.group(1)).is_file():
        raise SystemExit("no game folder resolved yet: run tools/codegen.ps1 -GameRoot <dir>")
    manifest = tomllib.loads(manifest_path(image.group(1)).read_text(encoding="utf-8"))
    return Path(manifest["project"]["game_root"])


def write(path: Path, text: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return True


def posix(path: Path) -> str:
    return path.resolve().as_posix()


def rewrite_addresses(text: str, moved: dict[int, int]) -> str:
    """The analysis with every hex address literal outside comments moved. Stops on one without
    a port, and on an address field that did not come out moved (written some other way)."""
    out = []
    unknown = []
    for line in text.splitlines():
        code, sep, comment = line.partition("#")

        def move(match):
            address = int(match.group(0), 16)
            if address not in moved:
                unknown.append(f"0x{address:08X} in: {line.strip()}")
                return match.group(0)
            return f"0x{moved[address]:08X}"

        out.append(ADDRESS.sub(move, code) + sep + comment)
    if unknown:
        raise SystemExit("main-xex.toml names addresses code_images.py does not collect:\n  " +
                         "\n  ".join(unknown))
    resolved = "\n".join(out) + "\n"
    unmoved = [f"{label} 0x{before:08X}" for (label, before), (_, after) in zip(
        ci.analysis_addresses(tomllib.loads(text)), ci.analysis_addresses(tomllib.loads(resolved)))
               if moved.get(before) != after]
    if unmoved:
        raise SystemExit("main-xex.toml addresses not moved (not a hex literal, or no port): " +
                         ", ".join(unmoved))
    return resolved


def resolved_analysis(image: str, moved: dict[int, int]) -> str:
    return "\n".join([f"# Generated by tools/release_analysis.py for code image {image} from",
                      "# config/rexglue/analysis/main-xex.toml: do not edit. Comments keep 1.0 addresses.",
                      f'includes = ["{posix(fragments_path(image))}"]', "",
                      rewrite_addresses(ci.MAIN_ANALYSIS.read_text(encoding="utf-8"), moved)])


def manifest(image: str, game_root: Path) -> str:
    text = MANIFEST_TEMPLATE.read_text(encoding="utf-8")
    text = text.replace(TEMPLATE_GAME_ROOT, posix(game_root))
    text = text.replace('"../../.local/generated/', '"')
    for name in ("speech-facade.toml", "xmedia-facade.toml"):
        text = text.replace(f'"analysis/{name}"', f'"{posix(ci.REXGLUE_CONFIG / "analysis" / name)}"')
    return text


def header(image: str, moved: dict[int, int]) -> str:
    guest = tomllib.loads(ci.GUEST_ADDRESSES.read_text(encoding="utf-8"))
    lines = [f"// Generated by tools/release_analysis.py for code image {image}: do not edit.",
             "#pragma once", "", "#include <cstdint>", "#include <string_view>", "",
             '#include "code_image_check.h"', "", "namespace fm4_guest {", "",
             f'inline constexpr std::string_view kCodeImage = "{image}";', "",
             "inline constexpr fm4_static_recomp::DiscRelease kReleases[] = {"]
    for release in ci.releases():
        sha = next(f["sha256"] for f in release["files"] if f["path"] == ci.EXECUTABLE)
        lines.append(f'    {{"{release["name"]}", "{release["code_image"]}", "{sha}"}},')
    lines += ["};", ""]
    for kind in ("code", "data"):
        for name, address in guest.get(kind, {}).items():
            lines.append(f"inline constexpr uint32_t {name} = 0x{moved[address]:08X};")
    lines += ["", "}  // namespace fm4_guest", ""]
    return "\n".join(lines)


def resolve(game_root: Path) -> str:
    release = ci.identify(game_root)
    image = release.image
    if not fragments_path(image).is_file():
        raise SystemExit(f"code image {image} has no fragment list "
                         f"{fragments_path(image).relative_to(ci.ROOT)}")
    moved = ci.address_map(image)
    folder = image_dir(image)
    changed = [p.relative_to(ci.ROOT) for p, text in (
        (folder / "analysis/main-xex.toml", resolved_analysis(image, moved)),
        (manifest_path(image), manifest(image, game_root)),
        (folder / "guest_addresses.h", header(image, moved)),
        (SELECTOR, f'set(FM4_CODE_IMAGE "{image}")\n'),
    ) if write(p, text)]
    print(f"{release.name}: code image {image}" +
          (f", rewrote {', '.join(str(p) for p in changed)}" if changed else ", unchanged"))
    return image


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    group = ap.add_mutually_exclusive_group(required=True)
    group.add_argument("--game-root", type=Path)
    group.add_argument("--refresh", action="store_true")
    args = ap.parse_args()
    resolve((args.game_root or current_game_root()).resolve())


if __name__ == "__main__":
    main()
